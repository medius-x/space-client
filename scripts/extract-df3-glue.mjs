/**
 * Vendor the DeepFilterNet3 wasm-bindgen worklet glue out of the npm package
 * into src/media/df3-glue.ts as a plain string module. Two reasons it cannot
 * be imported at runtime: the package's exports map blocks deep imports (no
 * ?raw on dist/*), and a ?raw-FILE import of a project file OUTSIDE the
 * renderer root is not rewritten by the vite dev import analyzer (the raw URL
 * falls through to the SPA html fallback — a live-caught blob syntax error).
 * And only the GLUE is kept (initSync, df_create, df_get_frame_length,
 * df_process_frame, df_set_atten_lim) — the package's own processor silently
 * swallows boot errors into a passthrough; ours lives in noise-suppression.ts.
 *
 * Run after every `npm update deepfilternet3-noise-filter`: `npm run df3:glue`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageEsm = join(scriptDir, "..", "node_modules", "deepfilternet3-noise-filter", "dist", "index.esm.js");
const outFile = join(scriptDir, "..", "src", "media", "df3-glue.ts");

const packaged = readFileSync(packageEsm, "utf8");
const marker = "var workletCode = ";
const literalStart = packaged.indexOf(marker) + marker.length;
const literalEnd = packaged.indexOf('";', literalStart);
if (literalStart === marker.length - 1 || literalEnd === -1) {
  throw new Error("workletCode literal not found — package layout changed");
}
const workletSource = JSON.parse(packaged.slice(literalStart, literalEnd + 1));
const cutAt = workletSource.indexOf("const WorkletMessageTypes");
if (cutAt === -1) {
  throw new Error("processor marker not found — package layout changed");
}
const glue = `${workletSource.slice(0, cutAt)}\n`;

const header = [
  "// GENERATED by scripts/extract-df3-glue.mjs (npm run df3:glue) — DO NOT EDIT.",
  "// The wasm-bindgen df glue (an IIFE PREFIX — it is closed by our processor",
  "// append in noise-suppression.ts). String module: see the generator's header",
  "// for why this is not a runtime ?raw import.",
  "",
].join("\n");

writeFileSync(outFile, `${header}export default ${JSON.stringify(glue)};\n`);
console.log(`df3 glue vendored: ${glue.length} chars → ${outFile}`);
