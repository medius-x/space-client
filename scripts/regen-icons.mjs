/**
 * Regenerates src/renderer/styles/icons.css from the installed @mdi/font package
 * (npm i --save-dev @mdi/font; MDI 7.4.47 — every modern glyph exists, no more
 * oak-era aliases or hand-embedded SVG paths). The class list is harvested from
 * the source itself, so a newly used `mdi-*` name just needs a re-run.
 *
 *   node scripts/regen-icons.mjs
 */
import { readdirSync, readFileSync, writeFileSync, copyFileSync, statSync, unlinkSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const FONT_DIR = join(ROOT, "node_modules", "@mdi", "font");
const CSS_PATH = join(FONT_DIR, "css", "materialdesignicons.css");
const OUT_CSS = join(ROOT, "src", "renderer", "styles", "icons.css");
const FONTS_OUT_DIR = join(ROOT, "src", "renderer", "styles", "fonts");

/** Every `mdi-<name>` token used anywhere under src/ (TS/TSX class strings + CSS selectors). */
function harvestUsedNames() {
  const used = new Set();
  const walk = (directory) => {
    for (const entry of readdirSync(directory)) {
      const fullPath = join(directory, entry);
      if (statSync(fullPath).isDirectory()) {
        walk(fullPath);
        continue;
      }
      if (!/\.(ts|tsx|css)$/.test(entry) || entry === "icons.css") {
        continue; // icons.css is THIS generator's output — it must not feed its own list
      }
      for (const match of readFileSync(fullPath, "utf8").matchAll(/mdi-([a-z0-9-]+)/g)) {
        used.add(match[1]);
      }
    }
  };
  walk(join(ROOT, "src"));
  // The generated css itself is a source file — ignore whatever it currently lists.
  return new Set([...used].filter((name) => name !== "name"));
}

/** name → content string, from the package css (`.mdi-<name>::before { content: "..." }`). */
function parseCodepoints() {
  const codepoints = new Map();
  const css = readFileSync(CSS_PATH, "utf8");
  for (const match of css.matchAll(/\.mdi-([a-z0-9-]+)::before\s*\{\s*content:\s*("[^"]+")/g)) {
    codepoints.set(match[1], match[2]);
  }
  return codepoints;
}

const used = harvestUsedNames();
const codepoints = parseCodepoints();

const missing = [...used].filter((name) => !codepoints.has(name));
if (missing.length > 0) {
  console.error(`Missing from @mdi/font: ${missing.join(", ")}`);
  process.exit(1);
}

const lines = [
  `/* Auto-generated by scripts/regen-icons.mjs from @mdi/font ${readFileSync(join(FONT_DIR, "package.json"), "utf8").match(/"version":\s*"([^"]+)"/)[1]} — do not edit by hand. */`,
  ``,
  `@font-face {`,
  `  font-family: "Material Design Icons";`,
  `  src: url("fonts/MaterialDesignIcons.woff2") format("woff2");`,
  `  font-weight: 400;`,
  `}`,
  ``,
  `.icon {`,
  `  font-family: "Material Design Icons";`,
  `  font-weight: normal;`,
  `  font-style: normal;`,
  `  line-height: 1;`,
  `  display: inline-flex;`,
  `  align-items: center;`,
  `  justify-content: center;`,
  `  -webkit-font-smoothing: antialiased;`,
  `  speak: never;`,
  `}`,
];
for (const name of [...used].sort()) {
  lines.push(`.icon.mdi-${name}::before { content: ${codepoints.get(name)}; }`);
}
writeFileSync(OUT_CSS, `${lines.join("\n")}\n`);

copyFileSync(join(FONT_DIR, "fonts", "materialdesignicons-webfont.woff2"), join(FONTS_OUT_DIR, "MaterialDesignIcons.woff2"));
// Electron renders through Chromium only — the woff2 alone covers it (a ttf
// fallback would just drag another megabyte into the bundle).
try {
  unlinkSync(join(FONTS_OUT_DIR, "MaterialDesignIcons.ttf"));
} catch {
  // nothing to clean up
}

console.log(`icons.css regenerated: ${used.size} glyphs; woff2 copied to styles/fonts/`);
