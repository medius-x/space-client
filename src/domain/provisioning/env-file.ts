/**
 * The /opt/oak/.env generator (provisioning, round C): every secret is random
 * per deployment — the dev defaults from oak-server's env/.env.example must
 * NEVER reach a real server. The only caller-supplied values are the public
 * host (an IP or a domain, validated to a shell-safe charset upstream) and
 * derived addresses; everything else comes from the injected random source.
 */

export interface EnvSecrets {
  postgresPassword: string;
  minioRootPassword: string;
  minioAppPassword: string;
  jwtSecret: string;
  janusAdminSecret: string;
  turnStaticAuthSecret: string;
}

/** A random source the tests can pin: `openssl rand -hex 32` equivalent. */
export type RandomHexSource = (bytes: number) => string;

export function generateEnvSecrets(randomHex: RandomHexSource): EnvSecrets {
  return {
    // 16 bytes (32 chars) is plenty for database/object-store credentials.
    postgresPassword: randomHex(16),
    minioRootPassword: randomHex(16),
    minioAppPassword: randomHex(16),
    // The HMAC keys guarding JWT issuance, the Janus admin API and TURN
    // tickets get the full 32 bytes.
    jwtSecret: randomHex(32),
    janusAdminSecret: randomHex(32),
    turnStaticAuthSecret: randomHex(32),
  };
}

/**
 * Builds the .env contents. `publicHost` is what clients type to reach this
 * server — a bare IP (self-signed certificate + TOFU pin) or a domain (the
 * certificate path is decided elsewhere; the file stays identical).
 * `turnExternalIp` is the server's raw address: coturn's --external-ip wants
 * the reachable IP even when the public address is a domain.
 */
export function buildEnvFile(publicHost: string, turnExternalIp: string, secrets: EnvSecrets): string {
  return [
    "# OAK deployment environment — generated by the space client's provisioning",
    "# flow. Secrets are random per deployment; do not commit or share them.",
    "",
    "# PostgreSQL",
    "POSTGRES_USER=oak",
    `POSTGRES_PASSWORD=${secrets.postgresPassword}`,
    "POSTGRES_DB=oak",
    "",
    "# MinIO (root credentials are console/bootstrap-only; oak-server signs with",
    "# the scoped app user created by the minio-init one-shot service).",
    "MINIO_ROOT_USER=oak_minio",
    `MINIO_ROOT_PASSWORD=${secrets.minioRootPassword}`,
    "MINIO_APP_USER=oak_app",
    `MINIO_APP_PASSWORD=${secrets.minioAppPassword}`,
    "",
    "# Janus — the admin secret guards the Admin API AND derives every",
    "# videoroom pin/secret inside oak-server.",
    `JANUS_ADMIN_SECRET=${secrets.janusAdminSecret}`,
    "",
    "# Coturn — short-lived REST-API credentials signed with this secret.",
    "TURN_REALM=oak.local",
    `TURN_STATIC_AUTH_SECRET=${secrets.turnStaticAuthSecret}`,
    "# The address clients use to reach Coturn (this server's reachable IP).",
    `TURN_EXTERNAL_IP=${turnExternalIp}`,
    "TURN_LISTEN_PORT=34780",
    "TURN_TLS_PORT=5349",
    "# Relay UDP port range — must match the mapped range in docker-compose.yml.",
    "TURN_MIN_PORT=55000",
    "TURN_MAX_PORT=55050",
    "",
    "# oak-server (prod profile requires the JWT secret).",
    `JWT_SECRET=${secrets.jwtSecret}`,
    "",
    "# The address clients use to reach this deployment.",
    `OAK_PUBLIC_HOST=${publicHost}`,
    "OAK_HTTPS_PORT=443",
    "OAK_MINIO_HTTPS_PORT=9443",
    "OAK_SITE_ADDRESS=https://" + publicHost,
    "OAK_MINIO_SITE_ADDRESS=https://" + publicHost + ":9443",
    "",
  ].join("\n");
}
